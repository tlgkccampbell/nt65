namespace Norristown.Tests.Emit;

/// <summary>
/// That the check over every fixture's and every corpus program's output can fail at all.
/// It is the check itself under test here, not the emitter: a check that passes because it
/// looks at nothing is how the alias mnemonics stayed hidden.
/// </summary>
public sealed class BareNameTests
{
    private const string Header = "; Generated by nt65 from main.nt65. Do not edit.\n.setcpu \"65816\"\n";

    [Fact]
    public void ADefinitionSpelledLikeAnInstructionIsFound()
    {
        Assert.Collection(
            BareNames.Problems("test", "main.s", Header + "swa = $12\ntad:\n    nop\n"),
            first => Assert.Contains("main.s:3: `swa` is an instruction", first, StringComparison.Ordinal),
            second => Assert.Contains("main.s:4: `tad` is an instruction", second, StringComparison.Ordinal));
    }

    /// <summary>
    /// The same words on a CPU whose ca65 table has none of them, a use rather than a
    /// definition, and a name that only starts with one, are all left alone.
    /// </summary>
    [Fact]
    public void AnythingCa65WouldNotMisreadIsLeftAlone()
    {
        Assert.Empty(BareNames.Problems("test", "main.s",
            Header.Replace("65816", "6502", StringComparison.Ordinal) + "swa = $12\ntad:\n"));
        Assert.Empty(BareNames.Problems("test", "main.s",
            Header + "main__swa = $12\nswap:\n    lda swa\n    jmp tad\n"));
        Assert.Empty(BareNames.Problems("test", "main.s.lines", "version 1\nfile 0, \"main.nt65\", 12\n"));
    }
}
