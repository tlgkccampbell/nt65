using Norristown.Emit;

namespace Norristown.Tests.Emit;

/// <summary>
/// Checks the line map written beside a generated <c>.s</c>, which records the source line each
/// output line came from, since the output itself does not.
/// </summary>
public sealed class LineMapTests
{
    private const string Program = """
        .module main
        .segment CODE
        .export .proc start {
            lda #1
            rts
        }
        """;

    /// <summary>
    /// A map names the source, its size, each line of the output that makes bytes, and the path
    /// of each value the output defines.
    /// </summary>
    [Fact]
    public void TheMapNamesTheSourceAndEveryLineThatMakesBytes()
    {
        var (code, map) = Compiled(Program);

        Assert.Equal(".lines", LineMap.Extension);
        Assert.Equal(code.Path + ".lines", map.Path);
        Assert.Equal(OutputKind.LineMap, map.Kind);
        Assert.StartsWith("; Generated by nt65 from main.nt65. Do not edit.\nversion 2\n", map.Text);
        Assert.Contains($"file 0, \"main.nt65\", {Program.Length}\n", map.Text);
        Assert.EndsWith("name main__start, main::start\n", map.Text);

        // `lda #1` and `rts` are the only lines that make bytes. The label and the header do not.
        var lines = map.Text.Split('\n').Where(line => line.StartsWith("line ", StringComparison.Ordinal)).ToList();
        Assert.Equal(2, lines.Count);
        var output = code.Text.Split('\n');
        foreach (var line in lines)
        {
            var fields = line["line ".Length..].Split(',').Select(field => field.Trim()).ToList();
            var source = Program.Split('\n')[int.Parse(fields[2]) - 1].Trim();
            Assert.Equal(source, output[int.Parse(fields[0]) - 1].Trim());
        }
    }

    /// <summary>A map reads back as the sources and line mappings it was written from.</summary>
    [Fact]
    public void AMapReadsBackAsWhatItWasWrittenFrom()
    {
        var (code, map) = Compiled(Program);

        Assert.True(LineMap.TryRead(map.Text, out var read, out var problem), problem);
        Assert.Null(problem);
        Assert.Equal([("main.nt65", Program.Length)], read.Sources);
        foreach (var (at, from) in read.Lines)
            Assert.Equal((0, code.LineSources[at - 1]), from);
        Assert.Equal(code.LineSources.Count(line => line != 0), read.Lines.Count);
        Assert.Equal(new Dictionary<string, string> { ["main__start"] = "main::start" }, read.Names);
    }

    /// <summary>
    /// A name the module keeps to itself is spelled in the output as the source spells it, and the
    /// map gives it the path that tells it apart from another module's name.
    /// </summary>
    [Fact]
    public void APrivateNameIsGivenItsModulesPath()
    {
        var (_, map) = Compiled("""
            .module wave
            .segment BSS
            .data shown: .byte
            .segment CODE
            .export .proc show {
                .scope inner {
                    .const STEP = 2
                }
                lda #inner::STEP
                sta shown
                rts
            }
            """);

        Assert.Contains("name shown, wave::shown\n", map.Text);
        Assert.Contains("name wave__show, wave::show\n", map.Text);
        Assert.Contains("name show__inner__STEP, wave::show::inner::STEP\n", map.Text);
    }

    /// <summary>
    /// A module that makes no bytes maps no lines, and its map gives only the paths of the values
    /// it defines, such as the registers of a module of nothing but hardware addresses.
    /// </summary>
    [Fact]
    public void AModuleThatMakesNoBytesMapsOnlyItsNames()
    {
        var compilation = Compiler.Compile([new SourceFile("main.nt65", ".module main\n.export .const VALUE = 7\n")]);

        Assert.Empty(compilation.Diagnostics);
        var map = Assert.Single(compilation.Outputs, output => output.Kind == OutputKind.LineMap);
        Assert.DoesNotContain("\nline ", map.Text);
        Assert.EndsWith("name main__VALUE, main::VALUE\n", map.Text);
    }

    /// <summary>
    /// Anything that is not a map nt65 wrote is refused rather than half read: a debug file is
    /// worth nothing if it is quietly wrong about where the bytes came from.
    /// </summary>
    [Theory]
    [InlineData("file 0, \"main.nt65\", 12\n", "no `version` record")]
    [InlineData("version 1\nfile 0, \"main.nt65\", 12\n", "version 1 line map")]
    [InlineData("version 2\nfile 1, \"main.nt65\", 12\n", "found `file 1` where `file 0` was expected")]
    [InlineData("version 2\nline 3, 0, 4\n", "no `file` record declares")]
    [InlineData("version 2\nwhat 3\n", "is not a line map record")]
    [InlineData("version 2\nfile 0, main.nt65, 12\n", "is not a line map record")]
    [InlineData("version 2\nname shown\n", "is not a line map record")]
    public void WhatIsNotAMapIsRefused(string text, string expected)
    {
        Assert.False(LineMap.TryRead(text, out var read, out var problem));
        Assert.Null(read);
        Assert.Contains(expected, problem);
    }

    /// <summary>Returns the ca65 output and the line map that a one-file program compiles to.</summary>
    private static (OutputFile Code, OutputFile Map) Compiled(string source)
    {
        var compilation = Compiler.Compile([new SourceFile("main.nt65", source)]);
        Assert.Empty(compilation.Diagnostics);
        return (Assert.Single(compilation.Ca65),
            Assert.Single(compilation.Outputs, o => o.Kind == OutputKind.LineMap));
    }
}
