using Norristown.Cli;

namespace Norristown.Tests.Cli;

/// <summary>
/// Tests <c>nt65 remap-dbg</c>, covering the command, the files it finds, and what it reports
/// when it cannot remap a file.
/// </summary>
public sealed class RemapCommandTests : IDisposable
{
    private const string Linked = """
        version	major=2,minor=0
        info	csym=0,file=1,lib=0,line=1,mod=1,scope=0,seg=1,span=1,sym=0,type=0
        file	id=0,name="build/main.s",size=200,mtime=0x12345678,mod=0
        line	id=0,file=0,line=4,span=0
        mod	id=0,name="main.o",file=0
        span	id=0,seg=0,start=0,size=2

        """;

    private const string Map = """
        ; Generated by nt65 from src/main.nt65. Do not edit.
        version 2
        file 0, "src/main.nt65", 300
        line 4, 0, 9

        """;

    private readonly TempFolder root = new("nt65-remap-");

    public void Dispose() => root.Dispose();

    /// <summary>
    /// The line map is found beside the <c>.s</c> the debug file names, whose path is relative to
    /// the directory the build ran in, and the debug file is rewritten in place.
    /// </summary>
    [Fact]
    public void TheDebugFileIsRemappedInPlaceFromTheMapBesideTheOutput()
    {
        root.Write("build/main.s.lines", Map);
        root.Write("game.dbg", Linked);

        var (code, printed) = Nt65.Run(root.FullName, "remap-dbg", "game.dbg");

        Assert.Equal((ExitCode.Success, ""), (code, printed));
        Assert.Contains("name=\"src/main.nt65\"", Read("game.dbg"));
        Assert.Contains("line\tid=1,file=1,line=9,type=1,span=0", Read("game.dbg"));
    }

    /// <summary><c>--out</c> writes somewhere else, and what ld65 wrote is left as it was.</summary>
    [Fact]
    public void OutWritesElsewhereAndLeavesTheOriginal()
    {
        root.Write("build/main.s.lines", Map);
        root.Write("game.dbg", Linked);

        Assert.Equal(ExitCode.Success, Nt65.Run(root.FullName, "remap-dbg", "game.dbg", "--out", "mapped.dbg").Code);

        Assert.Equal(Linked, Read("game.dbg"));
        Assert.Contains("name=\"src/main.nt65\"", Read("mapped.dbg"));
    }

    /// <summary>
    /// A debug file whose <c>.s</c> has no line map beside it was not built from nt65 output, and
    /// is left unchanged.
    /// </summary>
    [Fact]
    public void ADebugFileWithNoMapIsLeftAlone()
    {
        root.Write("game.dbg", Linked);

        Assert.Equal(ExitCode.Success, Nt65.Run(root.FullName, "remap-dbg", "game.dbg").Code);

        Assert.Equal(Linked, Read("game.dbg"));
    }

    /// <summary>
    /// <c>--labels</c> writes a label file that names each value by its path. Two modules' private
    /// names, which ld65 has under the same name, are told apart by their modules. A name the maps
    /// do not give is left out, and hand-written ca65 keeps its labels' own names.
    /// </summary>
    [Fact]
    public void LabelsNameEachValueByItsPath()
    {
        root.Write("build/main.s.lines", """
            version 2
            file 0, "src/main.nt65", 300
            name main__start, main::start
            name shown, main::shown

            """);
        root.Write("build/wave.s.lines", """
            version 2
            file 0, "src/wave.nt65", 200
            name shown, wave::shown
            name wave__LINES, wave::LINES

            """);
        root.Write("game.dbg", """
            version	major=2,minor=0
            info	csym=0,file=3,lib=0,line=0,mod=3,scope=3,seg=0,span=0,sym=8,type=0
            file	id=0,name="build/main.s",size=200,mtime=0x12345678,mod=0
            file	id=1,name="build/wave.s",size=200,mtime=0x12345678,mod=1
            file	id=2,name="asm/crt0.s",size=100,mtime=0x12345678,mod=2
            mod	id=0,name="main.o",file=0
            mod	id=1,name="wave.o",file=1
            mod	id=2,name="crt0.o",file=2
            scope	id=0,name="",mod=0
            scope	id=1,name="",mod=1
            scope	id=2,name="",mod=2
            sym	id=0,name="main__start",addrsize=absolute,scope=0,def=0,val=0x8000,seg=0,type=lab
            sym	id=1,name="shown",addrsize=absolute,scope=0,def=0,val=0x0200,seg=0,type=lab
            sym	id=2,name="shown",addrsize=absolute,scope=1,def=0,val=0x0201,seg=0,type=lab
            sym	id=3,name="wave__LINES",addrsize=zeropage,scope=1,def=0,val=0xE0,type=equ
            sym	id=4,name="wave__LINES",addrsize=zeropage,scope=0,def=0,val=0xE0,type=equ
            sym	id=5,name="build__loop",addrsize=absolute,scope=0,def=0,val=0x8004,seg=0,type=lab
            sym	id=6,name="reset",addrsize=absolute,scope=2,def=0,val=0xFF00,seg=0,type=lab
            sym	id=7,name="main__start",addrsize=absolute,scope=2,ref=0,type=imp

            """);

        Assert.Equal((ExitCode.Success, ""), Nt65.Run(root.FullName, "remap-dbg", "game.dbg", "--labels", "game.lbl"));

        Assert.Equal("""
            al 0000E0 .wave::LINES
            al 000200 .main::shown
            al 000201 .wave::shown
            al 008000 .main::start
            al 00FF00 .reset

            """, Read("game.lbl"));
    }

    /// <summary>Each failure is reported, naming the file it concerns where there is one.</summary>
    [Theory]
    [InlineData(new[] { "remap-dbg", "nowhere.dbg" }, ExitCode.InputError, "nowhere.dbg: error: file not found")]
    [InlineData(new[] { "remap-dbg" }, ExitCode.UsageError, "nt65: `remap-dbg` needs the debug file ld65 wrote with `--dbgfile`")]
    [InlineData(new[] { "remap-dbg", "a.dbg", "b.dbg" }, ExitCode.UsageError, "nt65: `remap-dbg` takes one debug file, and was given more than one")]
    [InlineData(new[] { "remap-dbg", "--out" }, ExitCode.UsageError, "nt65: `--out` needs a file to write")]
    [InlineData(new[] { "remap-dbg", "game.dbg", "--labels" }, ExitCode.UsageError, "nt65: `--labels` needs a file to write")]
    [InlineData(new[] { "remap-dbg", "--bogus", "game.dbg" }, ExitCode.UsageError, "nt65: `--bogus` is not an option")]
    public void EachFailureIsReportedWithItsExitCode(string[] arguments, ExitCode expected, string message)
    {
        root.Write("a.dbg", Linked);
        root.Write("game.dbg", Linked);

        var result = Nt65.Run(root.FullName, arguments);

        Assert.Equal(expected, result.Code);
        Assert.StartsWith(message, result.Printed);
    }

    /// <summary>A debug file that is not one ld65 wrote is refused rather than half rewritten.</summary>
    [Fact]
    public void SomethingThatIsNotADebugFileIsRefused()
    {
        root.Write("game.dbg", "not a debug file at all\n");

        var (code, printed) = Nt65.Run(root.FullName, "remap-dbg", "game.dbg");

        Assert.Equal(ExitCode.InputError, code);
        Assert.StartsWith("game.dbg: error: it is not a version 2.0 ld65 debug file", printed);
    }

    private string Read(string path) =>
        root.Read(path).ReplaceLineEndings("\n");
}
